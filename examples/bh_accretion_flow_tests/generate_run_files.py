def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def add_run(manifest: list[dict], *, family: str, tag: str, value: float,
            level: str, stage: str, end_myr: float, output_key: str) -> None:
    s = stem(family, tag, level)
    suffix = "diag" if stage == "diagnostic" else "evolve"
    param_rel = f"{family}/params/{s}_{suffix}.txt"
    out_rel = f"{family}/outputs/{suffix}/{s}"
    log_rel = f"{family}/logs/{suffix}/{s}.log"
    outputlist_rel = f"common/outputlists/{output_key}.txt"
    tmax = end_myr * CODE_PER_MYR

    # Diagnostic runs need only ~10 ceiling steps. Evolved runs use <=1% of
    # the intended physical duration; hydro/gravity criteria may reduce this.
    max_step = tmax / (10.0 if stage == "diagnostic" else 100.0)
    stats_step = max_step * 5.0

    write(HERE / param_rel, parameter_text(
        init_stem=ic_relpath(family, tag, level),
        output_dir=out_rel,
        output_list_file=outputlist_rel,
        time_max=tmax,
        max_step=max_step,
        statistics_step=stats_step,
    ))

    manifest.append({
        "family": family,
        "tag": tag,
        "control_value": value,
        "level": level,
        "stage": stage,
        "end_myr": end_myr,
        "time_max_code": tmax,
        "max_timestep_code": max_step,
        "parameter_file": param_rel,
        "output_list": outputlist_rel,
        "output_dir": out_rel,
        "log_file": log_rel,
        "recommended_ntasks": NTASKS[level],
        "selected_sink_model": "ffr-shell",
        "selected_sink_model_id": 4,
        "accretion_target": "direct",
        "feedback": "none",
        "eddington_factor": 1.0e-8,
    })


def main() -> None:
    # Shared output lists. Flag=2 is essential: it writes a full snapshot while
    # preventing the compiled FoF module from trying to build a DM catalogue.
    diag_end_myr = 0.001  # 1 kyr
    diag_end = diag_end_myr * CODE_PER_MYR
    write(HERE / "common/outputlists/diag_1kyr.txt", output_list([diag_end]))

    short_end_myr = 0.2   # 200 kyr perturbative rotation/turbulence evolution
    short_end = short_end_myr * CODE_PER_MYR
    write(HERE / "common/outputlists/evolve_200kyr.txt",
          output_list([short_end * f for f in (0.25, 0.50, 0.75, 1.0)]))

    bhl_end = {}
    for tag, mach in FAMILIES["bhl"]:
        if tag not in REPRESENTATIVE["bhl"]:
            continue
        end_myr = bhl_tacc_myr(mach)
        end_code = end_myr * CODE_PER_MYR
        key = f"evolve_bhl_{tag}"
        bhl_end[tag] = (end_myr, key)
        write(HERE / f"common/outputlists/{key}.txt",
              output_list([end_code * f for f in (0.25, 0.50, 0.75, 1.0)]))

    manifest: list[dict] = []

    # Stage B: exactly one passive startup run for every IC.
    for family, controls in FAMILIES.items():
        for tag, value in controls:
            for level in LEVELS:
                add_run(manifest, family=family, tag=tag, value=value,
                        level=level, stage="diagnostic",
                        end_myr=diag_end_myr, output_key="diag_1kyr")

    # Stage D: representative L1/L2 passive evolved-flow subset.
    for family, controls in FAMILIES.items():
        for tag, value in controls:
            if tag not in REPRESENTATIVE[family]:
                continue
            for level in ("L1", "L2"):
                if family == "bhl":
                    end_myr, key = bhl_end[tag]
                else:
                    end_myr, key = short_end_myr, "evolve_200kyr"
                add_run(manifest, family=family, tag=tag, value=value,
                        level=level, stage="evolved",
                        end_myr=end_myr, output_key=key)

    data = {
        "schema_version": 1,
        "myr_per_code_time": MYR_PER_CODE,
        "code_time_per_myr": CODE_PER_MYR,
        "diagnostic_count": sum(r["stage"] == "diagnostic" for r in manifest),
        "evolved_count": sum(r["stage"] == "evolved" for r in manifest),
        "total_count": len(manifest),
        "runs": manifest,
    }
    write(HERE / "run_manifest.json", json.dumps(data, indent=2, sort_keys=True) + "\n")

    print(f"Generated {data['diagnostic_count']} diagnostic parameter files")
    print(f"Generated {data['evolved_count']} representative evolved parameter files")
    print(f"Total planned runs: {data['total_count']}")
    print(f"1 code-time unit = {MYR_PER_CODE:.12g} Myr")
    for tag in sorted(bhl_end):
        print(f"BHL {tag}: t_end=t_acc={bhl_end[tag][0]:.9g} Myr")


if __name__ == "__main__":
    main()