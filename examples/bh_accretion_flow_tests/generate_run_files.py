# Code units used by the IC generator and parameter files.
UNIT_LENGTH_CGS = 3.085678e21       # 1 kpc
UNIT_MASS_CGS = 1.989e43            # 1e10 Msun
UNIT_VELOCITY_CGS = 1.0e5           # 1 km/s
SEC_PER_MYR = 1.0e6 * 365.25 * 86400.0
MYR_PER_CODE = (UNIT_LENGTH_CGS / UNIT_VELOCITY_CGS) / SEC_PER_MYR
CODE_PER_MYR = 1.0 / MYR_PER_CODE

R_ACC_PC = 12.5
BOX_PC = 100.0
BHL_CS_KMS = 5.0

LEVELS = ("L0", "L1", "L2")
